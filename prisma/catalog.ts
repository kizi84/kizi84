/**
 * The shop catalogue: category tree, brands and products.
 *
 * Kept apart from seed.ts so the art generator can read the same list and
 * render one packshot per item without duplicating the data.
 *
 * `art.shape` picks the packshot archetype (see scripts/art-kit.ts); `art.motif`
 * picks the illustration printed on it. Prices are quoted in лв. and converted
 * to euro on the way into the database.
 */

